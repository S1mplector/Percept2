void font_init(void) {
}

void font_draw_char(RendererPort* r, int x, int y, char c, Color color) {
    int index = c - 32;
    if (index < 0 || index >= 96) index = 0;
    
    const unsigned char* glyph = font_data[index];
    
    for (int row = 0; row < 8; row++) {
        unsigned char bits = glyph[row];
        for (int col = 0; col < 5; col++) {
            if (bits & (0x10 >> col)) {
                r->draw_rect_filled(r, x + col, y + row, 1, 1, color);
            }
        }
    }
}

void font_draw_string(RendererPort* r, int x, int y, const char* str, Color color) {
    int cx = x;
    while (*str) {
        font_draw_char(r, cx, y, *str, color);
        cx += FONT_CHAR_WIDTH;
        str++;
    }
}

void font_draw_string_centered(RendererPort* r, int x, int y, int width, const char* str, Color color) {
    int str_width = font_string_width(str);
    int start_x = x + (width - str_width) / 2;
    font_draw_string(r, start_x, y, str, color);
}

int font_string_width(const char* str) {
    return (int)strlen(str) * FONT_CHAR_WIDTH;
}
